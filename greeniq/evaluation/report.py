"""Render reports/EVALUATION.md from metrics. Every claim is computed from the metrics dict."""

from __future__ import annotations


def _f(x, nd=0, pct=False):
    if x is None:
        return "—"
    s = f"{x:,.{nd}f}"
    return s + ("%" if pct else "")


def _cmp(a, b, lower_better=True) -> str:
    if a is None or b is None:
        return "n/a"
    better = a < b if lower_better else a > b
    return "**better**" if better else "not better"


def _validation_section(v: dict, w) -> None:
    """PS2 §11 / §13G: the metrics and simple-baseline comparisons on the validation set."""
    w("## Validation set: metrics and simple baselines (PS2 §11, §13G)")
    w("")
    w("All tuning happened against this split (customer-grouped, no home or customer shared with train or test). "
      "Each GreenIQ method is set against a simple baseline.")
    w("")
    w("| Output | Metric | GreenIQ | Simple baseline | Result |")
    w("|---|---|---|---|---|")
    for fuel, r in v["energy"].items():
        t = r["validation"]
        w(f"| Baseline {fuel} (when meters are insufficient) | MAE kWh | {_f(t['gbm']['mae'])} | "
          f"{_f(t['peer_median']['mae'])} (peer median × area) | {_cmp(t['gbm']['mae'], t['peer_median']['mae'])} |")
    s = v["savings"]["methods"]
    for fuel in ("electricity", "gas"):
        w(f"| Retrofit saving, {fuel} ({v['savings']['cases']} observed retrofits) | MAE kWh | {_f(s['cal'][fuel]['mae'])} | "
          f"{_f(s['naive'][fuel]['mae'])} (flat % rule of thumb) | {_cmp(s['cal'][fuel]['mae'], s['naive'][fuel]['mae'])} |")
    if "hp_electricity_sign_correct" in s["cal"]:
        w(f"| Heat pump: electricity direction | % correct | {_f(100 * s['cal']['hp_electricity_sign_correct'], 0, True)} | "
          f"{_f(100 * s['naive']['hp_electricity_sign_correct'], 0, True)} | "
          f"{_cmp(s['cal']['hp_electricity_sign_correct'], s['naive']['hp_electricity_sign_correct'], False)} |")
    rk = v["ranking"]["methods"]
    g = rk["greeniq_improvement_potential"]
    for name in ("baseline_total_kwh (big-house trap)", "baseline_worst_epc_first"):
        b = rk[name]
        w(f"| Ranking poor homes ({v['ranking']['poor_homes_ranked']}) | Spearman vs true potential | "
          f"{_f(g['spearman_vs_true_potential'], 3)} | {_f(b['spearman_vs_true_potential'], 3)} ({name}) | "
          f"{_cmp(g['spearman_vs_true_potential'], b['spearman_vs_true_potential'], False)} |")
    r = v["rating"]
    w(f"| Energy rating when no EPC ({r['homes']} homes) | MAE SAP points | {_f(r['rating_model']['mae'], 1)} | "
      f"{_f(r['peer_median_baseline']['mae'], 1)} (peer median) | {_cmp(r['rating_model']['mae'], r['peer_median_baseline']['mae'])} |")
    cv = v["value_cv"]
    w(f"| Current value (grouped 5-fold CV, train+validation) | median APE | {_f(cv[v['value_chosen']]['median_ape_pct'], 1, True)} "
      f"({v['value_chosen']}) | {_f(cv['regional']['median_ape_pct'], 1, True)} (regional index) | "
      f"{_cmp(cv[v['value_chosen']]['median_ape_pct'], cv['regional']['median_ape_pct'])} |")
    sc, fe = v["score"], v["feasibility"]
    w("")
    w(f"Score: band agreement with the true inputs {_f(100 * sc['band_agreement'], 1, True)}; score ranges cover the "
      f"truth {_f(100 * (sc['partial_range_coverage'] or 0), 0, True)} of the time. Feasibility: recall "
      f"{_f(100 * fe['recall'], 1, True)}, unsuitable recommendations {_f(100 * fe['violation_rate'], 1, True)}. "
      f"{_f(v['ms_per_home_with_models'], 1)} ms per home.")
    w("")
    w("A \"not better\" row is reported as it is; where the simple baseline wins, the product uses it or labels the "
      "output as an estimate (see section 1).")
    w("")


def render(m: dict) -> str:
    L = []
    w = L.append
    w("# GreenIQ evaluation report (submission artifact G)")
    w("")
    w(f"> Generated by `uv run greeniq evaluate` · git `{m['git_commit']}` · models `{m['model_version']}` · "
      f"{m['evaluated_at']}. Every number below is regenerated from code on each run.")
    w(">")
    w("> **Read this first.** All data is synthetic (see [data/DATA_CARD.md](../data/DATA_CARD.md)). The test split "
      "(by customer) was scored **once**, after all tuning on the validation split. Agreement with the simulated world "
      "shows the method and pipeline work; **it is not evidence of real-world accuracy.**")
    w("")
    sc = m["split_counts"]
    w(f"Splits (by customer): train {sc.get('train')} · validation {sc.get('validation')} · test {sc.get('test')} homes.")
    w("")
    if "validation" in m:
        _validation_section(m["validation"], w)
    w("## Held-out test set (scored once, after all tuning)")
    w("")
    w("Sections 1-7 repeat the evaluation on the untouched **test** split, in more detail.")
    w("")

    # 1 energy ------------------------------------------------------------------------------
    w("## 1. Baseline energy per fuel (used when meters are insufficient)")
    w("")
    w("Target: weather-normalised annual purchased kWh from meters. Features: recorded characteristics only.")
    w("")
    for fuel, r in m["energy"].items():
        t = r["test"]
        w(f"**{fuel.capitalize()}** (test homes: {t['gbm']['n']})")
        w("")
        w("| Model | MAE kWh | RMSE kWh | R² | Median APE |")
        w("|---|---|---|---|---|")
        for name, key in [("Global median (naive)", "global_median"), ("Peer-group median × floor area (simple baseline)", "peer_median"),
                          ("Physics, RdSAP-lite (engineering baseline)", "physics"), ("Gradient boosting (GreenIQ)", "gbm")]:
            x = t[key]
            w(f"| {name} | {_f(x['mae'])} | {_f(x['rmse'])} | {_f(x['r2'], 3)} | {_f(x['median_ape_pct'], 1, True)} |")
        w("")
        g, p, ph = t["gbm"]["mae"], t["peer_median"]["mae"], t["physics"]["mae"]
        w(f"Gradient boosting vs the simple baseline: {_cmp(g, p)} ({_f(100 * (p - g) / p, 1)}% lower MAE). "
          f"vs physics: {_cmp(g, ph)} ({_f(100 * (ph - g) / ph, 1)}%).")
        w("")
        bt = r["gbm_median_ape_by_type"]
        w("Median APE by property type (bias check): " + " · ".join(f"{k} {_f(v, 1, True)}" for k, v in bt.items()))
        w("")
    w("*Interpretation.* The physics baseline is strong because the simulated world is physics-based; the remaining "
      "error is mostly occupant behaviour, which no characteristic can reveal. In the product these models are used "
      "only when a home lacks usable meter data, and their output is labelled **estimated**.")
    w("")

    # 2 savings -----------------------------------------------------------------------------
    s = m["savings"]
    w("## 2. Retrofit savings vs what homes actually saved")
    w("")
    w(f"Natural experiments: {s['cases']} test-split homes that installed a measure during the meter window. Observed "
      "saving = weather-normalised 12 months before − 12 months after. Predictions use only the pre-retrofit record "
      "and pre-retrofit meters.")
    w("")
    w("| Method | MAE electricity | MAE gas | Bias electricity | Bias gas | Heat-pump electricity sign correct |")
    w("|---|---|---|---|---|---|")
    names = {"naive": "Flat % of total energy (rule of thumb)", "eng": "GreenIQ engine, engineering",
             "cal": "GreenIQ engine, calibrated"}
    for k, label in names.items():
        x = s["methods"][k]
        w(f"| {label} | {_f(x['electricity']['mae'])} | {_f(x['gas']['mae'])} | {_f(x['electricity']['bias'])} | "
          f"{_f(x['gas']['bias'])} | {_f((x.get('hp_electricity_sign_correct') or 0) * 100, 0, True)} |")
    w("")
    if "heat_pump_cases" in s:
        w(f"Heat-pump cases: {s['heat_pump_cases']}; in {_f(s['heat_pump_observed_elec_increase_share'] * 100, 0, True)} "
          "of them electricity *rose* after installation. A fuel-blind rule of thumb cannot represent that; the per-fuel "
          "engine can.")
        w("")
    w("Net-saving MAE by measure (kWh/yr):")
    w("")
    w("| Measure | n | Observed mean net saving | Rule of thumb | Engineering | Calibrated |")
    w("|---|---|---|---|---|---|")
    for meas, x in s["per_measure"].items():
        w(f"| {meas} | {x['n']} | {_f(x['observed_net_mean'])} | {_f(x['naive_net_mae'])} | {_f(x['eng_net_mae'])} | "
          f"{_f(x['cal_net_mae'])} |")
    w("")
    v = m["validation_card"]
    w("Realisation rates learned on **train**, promoted on **validation** "
      f"(validation MAE elec+gas: uncalibrated {_f(v['calibration']['uncalibrated']['mae_total'])} → calibrated "
      f"{_f(v['calibration']['calibrated']['mae_total'])}):")
    w("")
    w("| Measure | Raw rate | n (train) | Shrunk rate used |")
    w("|---|---|---|---|")
    for meas, x in v["calibration_rates"].items():
        w(f"| {meas} | {x['raw_rate']:.2f} | {x['n_train']} | {x['rate']:.3f} |")
    w("")
    w("Rates below 1 mean real homes realise less than engineering physics predicts (installation quality, comfort "
      "take-back in previously under-heated homes). Small samples are shrunk toward 1.0.")
    w("")

    # 3 value -------------------------------------------------------------------------------
    va = m["value"]
    w("## 3. Property value")
    w("")
    w(f"Held-out test sales: {va['sales']} (prices converted to today's terms with the regional index). The current-value "
      "model is chosen by **customer-grouped 5-fold cross-validation over train+validation**:")
    w("")
    w("| Candidate | CV median APE | CV MAE £ | Test median APE | Test MAE £ |")
    w("|---|---|---|---|---|")
    for k, x in va["cv"].items():
        tst = va["test_all_candidates"].get(k)
        chosen = " **(chosen)**" if k == va["chosen"] else ""
        w(f"| {k}{chosen} | {_f(x['median_ape_pct'], 1, True)} | {_f(x['mae'])} | "
          f"{_f(tst['median_ape_pct'], 1, True) if tst else '—'} | {_f(tst['mae']) if tst else '—'} |")
    w("")
    if va.get("protocol_note"):
        w(f"> **Protocol disclosure.** {va['protocol_note']} The test figures in this section are therefore no longer a "
          "pristine held-out estimate for the value model. The energy, savings, ranking and score evaluations were not affected.")
        w("")
    iv = va["interval_80"]
    w(f"80% split-conformal interval (from out-of-fold residuals): empirical test coverage **{_f(iv['coverage'] * 100, 1, True)}**, "
      f"median width {_f(iv['median_width_pct'], 1, True)} of the estimate. Current value of test homes vs the hidden true "
      f"value: median APE {_f(va['current_value_vs_truth_median_ape_pct'], 1, True)} ({va['current_value_homes']} homes). "
      "Most remaining error is an unobservable location premium (σ ≈ 15% in the simulator), which no model of "
      "recorded characteristics can recover.")
    w("")
    w("EPC band premiums (hedonic regression on train+validation sales, vs band D; P10-P90 from a property-clustered "
      "bootstrap) next to the premiums **planted in the simulator**:")
    w("")
    w("| Band | Sales | Estimated premium | P10 | P90 | Planted |")
    w("|---|---|---|---|---|---|")
    for b, x in va["hedonic_premiums_vs_planted"].items():
        w(f"| {b} | {x['n_sales']} | {_f(x['premium_pct'], 1, True)} | {_f(x.get('p10'), 1, True)} | "
          f"{_f(x.get('p90'), 1, True)} | {_f(x['planted_pct'], 1, True)} |")
    w("")
    w("Recovering planted premiums shows the estimator works. It says nothing about the real-world premium, and it is "
      "associational, not causal. Uplift is therefore always shown as an **indicative range** with that caveat; bands "
      "with few sales get wide ranges.")
    w("")

    # 4 ranking -------------------------------------------------------------------------------
    rk = m["ranking"]
    w("## 4. Ranking poor homes by improvement potential")
    w("")
    w(f"{rk['poor_homes_ranked']} test homes flagged Poor/Very poor with a metered baseline. Ground truth: the "
      "simulator's counterfactual. Apply the same package to the *true* home and measure its true % reduction in "
      f"purchased energy. Top-20% = {rk['top_k']} homes.")
    w("")
    w("| Ranking criterion | Spearman vs true potential | Top-20% precision | Spearman with floor area |")
    w("|---|---|---|---|")
    for name, x in rk["methods"].items():
        w(f"| {name} | {_f(x['spearman_vs_true_potential'], 3)} | {_f(x['top20pct_precision'] * 100, 0, True)} | "
          f"{_f(x['spearman_with_floor_area'], 3)} |")
    w("")
    ta = rk["true_potential_spearman_with_floor_area"]
    big = rk["methods"]["baseline_total_kwh (big-house trap)"]["spearman_with_floor_area"]
    ours = rk["methods"]["greeniq_improvement_potential"]["spearman_with_floor_area"]
    w(f"Fairness yardstick (PS2: don't call a home inefficient because it is big): the *true* potential itself "
      f"correlates {_f(ta, 3)} with floor area in this world (bigger homes have more exposed fabric to fix). GreenIQ's "
      f"ranking correlates {_f(ours, 3)}; ranking by total kWh correlates {_f(big, 3)}, "
      + ("so total kWh over-weights size relative to the truth." if big > ta else "comparable to the truth."))
    w("")

    # 5 score -------------------------------------------------------------------------------
    so = m["score"]
    w("## 5. Green Home Score robustness to imperfect records")
    w("")
    w("The score is deterministic, so there is no model error to measure. What *can* go wrong is the input: missing "
      "fields, stale EPCs and wrong records. We compare the score computed from recorded data with the score the same "
      "formula gives on the true (hidden) state.")
    w("")
    w(f"- Homes with a point score: {so['point_scores']} · MAE vs true-input score **{_f(so['score_mae_vs_true_inputs'], 2)}** "
      f"points · band agreement **{_f(so['band_agreement'] * 100, 1, True)}** · MAE for `complete` records {_f(so['complete_only_mae'], 2)}")
    if so["partial_homes"]:
        w(f"- Homes reported as `partial` (range, no point score): {so['partial_homes']} · the true score falls inside "
          f"the reported range in **{_f(so['partial_range_coverage'] * 100, 1, True)}** of them")
    w("")

    # 6 feasibility ---------------------------------------------------------------------------
    fe = m["feasibility"]
    w("## 6. Retrofit feasibility")
    w("")
    w(f"Recommended measures checked against true feasibility on test homes: {fe['recommended']} recommendations, "
      f"**{fe['violations']} infeasible** (rate {_f(fe['violation_rate'] * 100, 2, True)}); recall of truly feasible "
      f"measures {_f(fe['recall'] * 100, 1, True)}. Of the infeasible recommendations, "
      f"{fe['violations_flagged_for_survey']} ({_f(100 * fe['violations_flagged_for_survey'] / max(fe['violations'], 1), 0, True)}) "
      "were already flagged to the customer as resting on assumed or unrecorded inputs (\"confirm by survey\"); the "
      "remainder were not flagged and arise from missing or incorrect record fields the planner treated as non-blocking.")
    w("")
    w("| Measure | Recommended | Infeasible | Truly feasible | Found |")
    w("|---|---|---|---|---|")
    for meas, x in fe["by_measure"].items():
        w(f"| {meas} | {x['recommended']} | {x['violations']} | {x['truly_feasible']} | {x['found']} |")
    w("")

    # 7 rating + conflicts --------------------------------------------------------------------
    ra = m["rating"]
    w("## 7. Estimating a missing EPC rating")
    w("")
    w(f"Recorded SAP hidden on {ra['homes']} test homes, then estimated:")
    w("")
    w("| Method | MAE (SAP points) | Band accuracy |")
    w("|---|---|---|")
    w(f"| Peer median (type × age), simple baseline | {_f(ra['peer_median_baseline']['mae'], 1)} | "
      f"{_f(ra['peer_median_baseline']['band_accuracy'] * 100, 1, True)} |")
    w(f"| SAP-style rating model (GreenIQ) | {_f(ra['rating_model']['mae'], 1)} | "
      f"{_f(ra['rating_model']['band_accuracy'] * 100, 1, True)} |")
    w("")
    co = m["conflicts"]
    w(f"**Conflict detection** (rule-based, no trained parameters, graded on all homes): planted wrong heating records "
      f"{co['heating_record_errors_planted']}, detected {co['detected']}, false alarms {co['false_alarms']} "
      f"(precision {_f(co['precision'] * 100, 1, True)}, recall {_f(co['recall'] * 100, 1, True)}).")
    w("")
    w(f"Pipeline speed with models attached: {_f(m['ms_per_home_with_models'], 1)} ms per home.")
    w("")
    w("## 8. Grounded language (ER-4)")
    w("")
    w("See §8 of this report once the language layer is evaluated (Phase 7).")
    w("")
    w("## 9. Limitations")
    w("")
    w("- Synthetic world: metrics measure the pipeline against a simulator, not reality.")
    w("- The simulator and the engine share well-established physics (heat loss, degree days); hidden behaviour, "
      "installation quality and record errors keep evaluation honest, but some optimism remains.")
    w("- Value premiums are associational; the planted premiums come from the literature's order of magnitude.")
    w("- Small samples: some measures have few historical retrofits; rates are shrunk toward the engineering estimate.")
    w("- Held-out predictions: [`test_predictions.csv`](test_predictions.csv), schema in "
      "[`TEST_PREDICTIONS_SCHEMA.md`](TEST_PREDICTIONS_SCHEMA.md).")
    w("")
    return "\n".join(L)
