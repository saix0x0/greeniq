"""Per-measure impact on the brief's own quantities (PS2 §4 illustrative table) → reports/RETROFIT_IMPACTS.md.

PS2 §4 gives illustrative impacts, each on its own quantity (space-heating demand, purchased energy,
grid imports, heating energy). Our catalogue's engineering parameters take precedence, so this report
documents what the engine actually predicts on the SAME quantity, over validation-split homes, beside
the brief's range and beside savings measured in real UK homes (DESNZ NEED), so the three can be read
together. Each measure is evaluated standalone (done alone on today's home), as the brief's rows are.
"""

from __future__ import annotations

import json

import numpy as np

from ..context import load_context
from ..data import ROOT, load_dataset, load_splits
from ..engines.catalogue import catalogue
from ..pipeline import analyse_home

REPORTS = ROOT / "reports"
REAL_KEY = {"loft_insulation": "loft", "cavity_wall_insulation": "cavity", "solar_pv": "solar_pv"}


def _pct(rec, f, quantity: str) -> float | None:
    """The measure's standalone saving as a % of the quantity the brief's row refers to."""
    sa, base = rec.standalone, f.baseline
    gas_heated = (f.property_summary.get("heating_system_recorded") or "").startswith("gas")
    if quantity in ("space-heating energy demand", "heating energy use"):
        if not gas_heated or not base["gas"].heating_kwh:
            return None  # heating fuel split only defined for gas-heated, metered homes here
        return 100 * (sa.gas.saving_kwh or 0) / base["gas"].heating_kwh
    if quantity.startswith("purchased energy"):
        e = (base["electricity"].annual_kwh or 0) + (base["gas"].annual_kwh or 0)
        return 100 * sa.net_saving_kwh / e if e else None
    if quantity == "grid electricity imports":
        e = base["electricity"].annual_kwh
        return 100 * (sa.electricity.saving_kwh or 0) / e if e else None
    return None


def evaluate_impacts(split: str = "validation") -> dict:
    ds, ctx, sp = load_dataset(), load_context(), load_splits()
    ids = sp.loc[sp["split"] == split, "property_id"].tolist()
    cat = catalogue()["measures"]
    real = {}
    rd = ROOT / "reports" / "real_data.json"
    if rd.exists():
        real = json.loads(rd.read_text()).get("retrofit_evidence", {})
    acc: dict[str, list[float]] = {m: [] for m, x in cat.items() if x.get("ps2_illustrative_impact")}
    for pid in ids:
        f = analyse_home(ds.property(pid), ctx)
        if f.baseline_basis != "metered":
            continue
        for r in f.plan:
            q = (cat[r.measure_id].get("ps2_illustrative_impact") or {}).get("quantity")
            if q:
                v = _pct(r, f, q)
                if v is not None:
                    acc[r.measure_id].append(v)
    out = {}
    for m, vals in acc.items():
        ill = cat[m]["ps2_illustrative_impact"]
        a = np.array(vals)
        ev = real.get(REAL_KEY.get(m, ""), {}).get("estimate")
        out[m] = {"name": cat[m]["name"], "quantity": ill["quantity"], "ps2_range_pct": [ill["low_pct"], ill["high_pct"]],
                  "homes": int(len(a)),
                  "engine_median_pct": round(float(np.median(a)), 1) if len(a) else None,
                  "engine_p25_p75_pct": [round(float(np.percentile(a, 25)), 1), round(float(np.percentile(a, 75)), 1)] if len(a) else None,
                  "real_homes": {"saving_pct": ev["saving_pct"], "of": real[REAL_KEY[m]]["fuel"] + (" use" if m != "solar_pv" else " imports"),
                                 "n": ev["n"]} if ev and ev.get("n") else None}
    return {"split": split, "calibration": ctx.calibration_name, "measures": out}


def render(r: dict) -> str:
    L = ["# Retrofit impacts on the brief's own quantities (PS2 §4)", "",
         "> Generated by `uv run greeniq evaluate`. Each measure done **alone** on today's home, over metered "
         f"**{r['split']}** homes, with the product's savings model ({r['calibration']}). The brief's figures are illustrative "
         "and each row refers to its own quantity; per PS2 §4 our catalogue takes precedence, so this table documents how "
         "the two compare. Real-home figures are measured in DESNZ NEED (difference-in-differences) on a related but not "
         "identical quantity, shown in the last column.", "",
         "| Measure | Quantity (as in the brief) | Brief's illustrative range | GreenIQ engine, median (25th–75th pct) | Homes | Measured in real homes |",
         "|---|---|---|---|---|---|"]
    for m in r["measures"].values():
        e = "—" if m["engine_median_pct"] is None else f"{m['engine_median_pct']}% ({m['engine_p25_p75_pct'][0]}–{m['engine_p25_p75_pct'][1]}%)"
        rh = f"{m['real_homes']['saving_pct']}% of {m['real_homes']['of']} (n={m['real_homes']['n']:,})" if m["real_homes"] else "—"
        L.append(f"| {m['name']} | {m['quantity']} | {m['ps2_range_pct'][0]}–{m['ps2_range_pct'][1]}% | {e} | {m['homes']} | {rh} |")
    L += ["", "Notes:", "",
          "- Space-heating and heating-energy percentages use gas-heated metered homes, where the meter regression splits gas "
          "into heating and the rest.",
          "- Loft, cavity and solar are corrected to what real UK homes achieved (median ÷ median realisation, "
          "reports/REAL_DATA.md); that is why solar sits well below the brief's 20-35% and close to the measured 9.75%.",
          "- Heat pump: the brief's 15-25% is far below our engine. Replacing a gas boiler (≈85-90% efficient) with a heat "
          "pump (seasonal COP 2.6-3.4 in our catalogue; 2.8 is the Boiler Upgrade Scheme minimum) divides the energy bought "
          "for heat by roughly three, so purchased kWh typically fall by half even though electricity rises. We keep the "
          "physics and flag the gap; there is no real UK heat-pump retrofit evidence in NEED to calibrate against.", ""]
    return "\n".join(L)


def write(split: str = "validation") -> dict:
    r = evaluate_impacts(split)
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "RETROFIT_IMPACTS.md").write_text(render(r), encoding="utf-8")
    return r
