"""Render reports/REAL_DATA.md. Every sentence is computed from the results dict."""

from __future__ import annotations


def _f(x, nd=0, pct=False):
    if x is None:
        return "—"
    return f"{x:,.{nd}f}" + ("%" if pct else "")


def render(o: dict) -> str:
    s, L = o["summary"], []
    w = L.append
    w("# Real-data evidence: DESNZ NEED, 50,000 real homes")
    w("")
    w("> Generated by `uv run python -m greeniq real-evidence`. Source: DESNZ National Energy Efficiency "
      "Data-Framework, anonymised 2026, 50,000-row sample. Contains public sector information licensed under the "
      f"Open Government Licence v3.0. File checksum verified: **{s['checksum_ok']}**. **These are real homes and real "
      "meter readings**, unlike the simulated portfolio used elsewhere in the app.")
    w("")
    w(f"Homes: {s['homes']:,} (split train {s['split'].get('train'):,} · validation {s['split'].get('validation'):,} · "
      f"test {s['split'].get('test'):,}). Valid 2024 readings: gas {s['valid_2024']['gas']:,} (median "
      f"{_f(s['median_2024']['gas'])} kWh), electricity {s['valid_2024']['electricity']:,} (median "
      f"{_f(s['median_2024']['electricity'])} kWh). Invalid, estimated or capped readings are treated as missing, "
      "never as zero.")
    w("")
    w("## 1. Predicting a home's energy use from its characteristics (real held-out homes)")
    w("")
    for fuel, r in o["energy"].items():
        t = r["test"]
        w(f"**{fuel.capitalize()}**: {r['rows']['test']:,} real test homes (trained on {r['rows']['train']:,}).")
        w("")
        w("| Model | MAE kWh | RMSE kWh | R² | Median APE |")
        w("|---|---|---|---|---|")
        for name, k in (("National median (naive)", "global_median"),
                        ("Median of similar homes (simple baseline)", "peer_median"),
                        ("Gradient boosting (GreenIQ)", "gbm")):
            x = t[k]
            w(f"| {name} | {_f(x['mae'])} | {_f(x['rmse'])} | {_f(x['r2'], 3)} | {_f(x['median_ape_pct'], 1, True)} |")
        g, p = t["gbm"]["mae"], t["peer_median"]["mae"]
        verdict = "beats" if g < p else "does not beat"
        w("")
        w(f"Gradient boosting **{verdict}** the similar-homes baseline on real held-out homes "
          f"({_f(100 * (p - g) / p, 1)}% lower MAE). Promoted on validation: **{r['promoted']}**. "
          "Median APE by type: " + " · ".join(f"{k} {_f(v, 1, True)}" for k, v in r["gbm_median_ape_by_type"].items()) + ".")
        w("")
    w("*Interpretation.* Characteristics explain only part of real energy use; occupants and behaviour explain "
      "the rest, so errors stay large even for the best model. That is why GreenIQ anchors savings on each home's "
      "**own meter readings** and uses these models only as a labelled estimate when readings are missing, and as "
      "the 'homes like yours' benchmark.")
    w("")
    w("## 2. What retrofits really saved (difference-in-differences on real installs)")
    w("")
    w("For each home that installed a measure in year *y*: the change in use from *y−1* to *y+1*, minus the "
      "same change in similar homes (type, age band, floor-area band, region) that never installed loft, cavity "
      "or solar, reported as the **median** over installers (robust to the few homes with tiny \"before\" use) with a "
      "bootstrap 90% interval. Gas is weather-corrected by DESNZ; solar is measured on grid electricity.")
    w("")
    w("| Measure | Fuel | Homes (train+val) | Real saving | 90% interval | ≈ kWh/yr | Test-split check | GreenIQ engine predicts | Realisation |")
    w("|---|---|---|---|---|---|---|---|---|")
    for m, r in o["retrofit_evidence"].items():
        e, c = r.get("estimate", {}), r.get("check", {})
        if not e.get("n"):
            w(f"| {m} | {r['fuel']} | 0 | — | — | — | — | — | — |")
            continue
        chk = f"{_f(c.get('saving_pct'), 1, True)} (n={c.get('n', 0)})" if c.get("n") else "—"
        w(f"| {m.replace('_', ' ')} | {r['fuel']} | {e['n']:,} | **{_f(e['saving_pct'], 1, True)}** | "
          f"{_f(e['ci90_pct'][0], 1)}% to {_f(e['ci90_pct'][1], 1)}% | {_f(e['saving_kwh'])} | {chk} | "
          f"{_f(r.get('engine_median_pct', r.get('engine_mean_pct')), 1, True)} | {_f(r.get('realisation_vs_engine'), 2)} |")
    w("")
    w("*Realisation* = real median saving ÷ the engine's median predicted saving for that measure across the app's homes "
      "(engineering estimate, uncalibrated). Below 1 means real installs save less than physics predicts. This is "
      "the well-known performance gap, which can come from top-up installs, comfort take-back or installation quality.")
    w("")
    w("## 3. Limitations")
    w("")
    w("- NEED has no wall type, loft depth, glazing, controls, boiler type, exact floor area or prices, so the "
      "app's detailed homes still come from the documented simulator. Every field is labelled.")
    w("- Install years are for the *latest* government-scheme install (it may be a top-up), and installers chose "
      "to install: the savings are observed associations with a matched comparison, not a randomised trial.")
    w("- Consumption is rounded to 100 kWh and capped (gas 1,000–50,000; electricity 500–25,000 kWh).")
    w("- Electricity is not weather-corrected; the matched comparison removes the shared year effect.")
    w("")
    return "\n".join(L)
